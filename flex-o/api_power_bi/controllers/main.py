    def days_between(self,d1):
        now = date.today()
        if str(now) <= str(d1) :
            return 'No Vencido'
        dias = abs(now - d1).days
        if dias >= 1 and dias <= 30:
            return "1 a 30 Dias Vencido"
        elif dias >= 31 and dias <= 60:
            return "31 a 60 Dias Vencido"
        elif dias >= 61 and dias <= 90:
            return "61 a 90 Dias Vencido"
        elif dias >= 91 and dias <= 120:
            return "91 a 120 Dias Vencido"
        else :
            return "mas de 121 Dias Vencido"
    def pagos(self,p):
        
        if p == "not_paid" :
            return "No Pagado"
        elif p == "in_payment":
            return "En proceso de pago"
        elif p  == "paid":
            return "Pagado"
        else :
            return ""

